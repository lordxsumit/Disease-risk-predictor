import React, { useState } from "react";
import { submitRiskAssessment } from "../src/api";

const initialData = {
  male: "",
  age: "",
  currentSmoker: "",
  cigsPerDay: "",
  BPMeds: "",
  prevalentStroke: "",
  prevalentHyp: "",
  diabetes: "",
  totChol: "",
  sysBP: "",
  diaBP: "",
  BMI: "",
  TenYearCHD: "",
};

function HeartRisk({
  predictedDisease = "Heart disease",
  parentPrediction,
  onBack,
}) {
  const [step, setStep] = useState(1);
  const [formData, setFormData] = useState(initialData);
  const [result, setResult] = useState(null);
  const [error, setError] = useState("");
  const [loading, setLoading] = useState(false);

  const updateField = (field, value) => {
    setFormData((prev) => ({
      ...prev,
      [field]: value,
    }));
  };

  const nextStep = () => {
    setStep((prev) => prev + 1);
  };

  const previousStep = () => {
    setStep((prev) => prev - 1);
  };

  const submitAssessment = async () => {
    setError("");
    const missingField = Object.entries(formData)
      .find(([, value]) => value.trim() === "");
    if (missingField) {
      setError("Please complete every field before calculating your risk.");
      return;
    }

    const payload = Object.fromEntries(
      Object.entries(formData).map(([field, value]) => [field, Number(value)]),
    );
    if (Object.values(payload).some((value) => !Number.isFinite(value))) {
      setError("Enter valid numbers for all measurements.");
      return;
    }
    if (!Number.isInteger(payload.age)) {
      setError("Age must be a whole number.");
      return;
    }

    setLoading(true);
    try {
      const riskResult = await submitRiskAssessment({
        type: "heart",
        predictedDisease,
        parentPrediction,
        inputData: payload,
      });
      setResult(riskResult);
      setStep(4);
    } catch (submitError) {
      setError(submitError.message || "Unable to calculate heart disease risk.");
    } finally {
      setLoading(false);
    }
  };

  const resetAssessment = () => {
    setStep(1);
    setFormData(initialData);
    setResult(null);
    setError("");
  };

  return (
    <div className="assessment-page">
      {/* HEADER */}

      <header className="assessment-header">
        <button
          className="back-button"
          onClick={onBack || (() => window.history.back())}
        >
          ← Back
        </button>

        <div className="header-title">
          <span className="medical-icon">♡</span>
          Disease Risk Predictor
        </div>
      </header>

      <main className="assessment-container">
        {/* RESULT */}

        {step === 4 && result ? (
          <div className="result-card">
            <div className="result-icon">
              {Number(result.risk_percentage) >= 50 ? "!" : "✓"}
            </div>

            <p className="small-heading">
              HEART DISEASE ASSESSMENT
            </p>

            <h1>
              Estimated 10-Year Risk
            </h1>

            <div className="risk-score">
              {Number(result.risk_percentage).toFixed(2)}%
            </div>

            <p className="score-label">
              Risk Score
            </p>

            <p className="result-description">
              This estimate is generated by the heart-risk model. It is not a
              medical diagnosis; please discuss health concerns with a
              qualified healthcare professional.
            </p>

            <button
              className="primary-button"
              onClick={resetAssessment}
            >
              Take Assessment Again
            </button>
          </div>
        ) : (
          <>
            {/* INTRO */}

            <div className="assessment-intro">
              <div>
                <p className="eyebrow">
                  RISK ASSESSMENT
                </p>

                <h1>
                  Heart Disease Risk Assessment
                </h1>

                <p>
                  Answer the following questions to assess
                  your heart disease risk.
                </p>
              </div>

              <div className="shield-icon">
                ♡
              </div>
            </div>

            {/* PROGRESS */}

            <div className="progress-section">
              <div className="progress-label">
                <span>
                  Step {step} of 3
                </span>

                <span>
                  {Math.round((step / 3) * 100)}%
                </span>
              </div>

              <div className="progress-track">
                <div
                  className="progress-fill"
                  style={{
                    width: `${(step / 3) * 100}%`,
                  }}
                />
              </div>
            </div>

            {/* STEP 1 */}

            {step === 1 && (
              <section className="question-card">
                <div className="section-heading">
                  <span className="section-number">
                    01
                  </span>

                  <div>
                    <h2>Basic Information</h2>

                    <p>
                      Tell us about your age, gender and
                      smoking status.
                    </p>
                  </div>
                </div>

                <div className="form-grid">
                  <Select
                    label="Gender"
                    value={formData.male}
                    onChange={(e) =>
                      updateField(
                        "male",
                        e.target.value
                      )
                    }
                    options={[
                      {
                        label: "Male",
                        value: "1",
                      },
                      {
                        label: "Female",
                        value: "0",
                      },
                    ]}
                  />

                  <Input
                    label="Age"
                    type="number"
                    placeholder="Enter age"
                    value={formData.age}
                    onChange={(e) =>
                      updateField(
                        "age",
                        e.target.value
                      )
                    }
                  />

                  <Select
                    label="Current Smoker"
                    value={
                      formData.currentSmoker
                    }
                    onChange={(e) =>
                      updateField(
                        "currentSmoker",
                        e.target.value
                      )
                    }
                    options={[
                      {
                        label: "Yes",
                        value: "1",
                      },
                      {
                        label: "No",
                        value: "0",
                      },
                    ]}
                  />

                  <Input
                    label="Cigarettes Per Day"
                    type="number"
                    placeholder="Enter number"
                    value={
                      formData.cigsPerDay
                    }
                    onChange={(e) =>
                      updateField(
                        "cigsPerDay",
                        e.target.value
                      )
                    }
                  />
                </div>

                <NavigationButton
                  onClick={nextStep}
                >
                  Continue →
                </NavigationButton>
              </section>
            )}

            {/* STEP 2 */}

            {step === 2 && (
              <section className="question-card">
                <div className="section-heading">
                  <span className="section-number">
                    02
                  </span>

                  <div>
                    <h2>Medical History</h2>

                    <p>
                      Provide information about your
                      existing health history.
                    </p>
                  </div>
                </div>

                <div className="form-grid">
                  <Select
                    label="Blood Pressure Medication"
                    value={formData.BPMeds}
                    onChange={(e) =>
                      updateField(
                        "BPMeds",
                        e.target.value
                      )
                    }
                    options={[
                      {
                        label: "Yes",
                        value: "1",
                      },
                      {
                        label: "No",
                        value: "0",
                      },
                    ]}
                  />

                  <Select
                    label="Previous Stroke"
                    value={
                      formData.prevalentStroke
                    }
                    onChange={(e) =>
                      updateField(
                        "prevalentStroke",
                        e.target.value
                      )
                    }
                    options={[
                      {
                        label: "Yes",
                        value: "1",
                      },
                      {
                        label: "No",
                        value: "0",
                      },
                    ]}
                  />

                  <Select
                    label="Hypertension"
                    value={
                      formData.prevalentHyp
                    }
                    onChange={(e) =>
                      updateField(
                        "prevalentHyp",
                        e.target.value
                      )
                    }
                    options={[
                      {
                        label: "Yes",
                        value: "1",
                      },
                      {
                        label: "No",
                        value: "0",
                      },
                    ]}
                  />

                  <Select
                    label="Diabetes"
                    value={formData.diabetes}
                    onChange={(e) =>
                      updateField(
                        "diabetes",
                        e.target.value
                      )
                    }
                    options={[
                      {
                        label: "Yes",
                        value: "1",
                      },
                      {
                        label: "No",
                        value: "0",
                      },
                    ]}
                  />

                  <Select
                    label="Have you had coronary heart disease in the past 10 years?"
                    value={formData.TenYearCHD}
                    onChange={(e) =>
                      updateField("TenYearCHD", e.target.value)
                    }
                    options={[
                      { label: "Yes", value: "1" },
                      { label: "No", value: "0" },
                    ]}
                  />
                </div>

                <NavigationButtons
                  onBack={previousStep}
                  onNext={nextStep}
                />
              </section>
            )}

            {/* STEP 3 */}

            {step === 3 && (
              <section className="question-card">
                <div className="section-heading">
                  <span className="section-number">
                    03
                  </span>

                  <div>
                    <h2>Health Measurements</h2>

                    <p>
                      Enter your available health
                      measurements.
                    </p>
                  </div>
                </div>

                <div className="form-grid">
                  <Input
                    label="Total Cholesterol"
                    type="number"
                    placeholder="Enter value"
                    value={formData.totChol}
                    onChange={(e) =>
                      updateField(
                        "totChol",
                        e.target.value
                      )
                    }
                  />

                  <Input
                    label="Systolic Blood Pressure"
                    type="number"
                    placeholder="e.g. 120"
                    value={formData.sysBP}
                    onChange={(e) =>
                      updateField(
                        "sysBP",
                        e.target.value
                      )
                    }
                  />

                  <Input
                    label="Diastolic Blood Pressure"
                    type="number"
                    placeholder="e.g. 80"
                    value={formData.diaBP}
                    onChange={(e) =>
                      updateField(
                        "diaBP",
                        e.target.value
                      )
                    }
                  />

                  <Input
                    label="BMI"
                    type="number"
                    step="0.1"
                    placeholder="Enter BMI"
                    value={formData.BMI}
                    onChange={(e) =>
                      updateField(
                        "BMI",
                        e.target.value
                      )
                    }
                  />
                </div>

                <div className="button-row">
                  <button
                    className="secondary-button"
                    onClick={previousStep}
                  >
                    ← Back
                  </button>

                  <button
                    className="primary-button"
                    onClick={submitAssessment}
                    disabled={loading}
                  >
                    {loading ? "Calculating..." : "Check Risk →"}
                  </button>
                </div>
                {error && <p role="alert">{error}</p>}
              </section>
            )}
          </>
        )}
      </main>
    </div>
  );
}

/* INPUT */

function Input({
  label,
  type,
  placeholder,
  value,
  onChange,
  step,
}) {
  return (
    <div className="field">
      <label>{label}</label>

      <input
        type={type}
        step={step}
        placeholder={placeholder}
        value={value}
        onChange={onChange}
      />
    </div>
  );
}

/* SELECT */

function Select({
  label,
  value,
  onChange,
  options,
}) {
  return (
    <div className="field">
      <label>{label}</label>

      <select value={value} onChange={onChange}>
        <option value="">
          Select {label}
        </option>

        {options.map((option) => (
          <option
            key={option.value}
            value={option.value}
          >
            {option.label}
          </option>
        ))}
      </select>
    </div>
  );
}

/* BUTTON */

function NavigationButton({
  children,
  onClick,
}) {
  return (
    <div className="button-row right">
      <button
        className="primary-button"
        onClick={onClick}
      >
        {children}
      </button>
    </div>
  );
}

/* NAVIGATION BUTTONS */

function NavigationButtons({
  onBack,
  onNext,
}) {
  return (
    <div className="button-row">
      <button
        className="secondary-button"
        onClick={onBack}
      >
        ← Back
      </button>

      <button
        className="primary-button"
        onClick={onNext}
      >
        Continue →
      </button>
    </div>
  );
}

export default HeartRisk;